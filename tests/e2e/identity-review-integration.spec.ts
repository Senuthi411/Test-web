import { expect, test } from '@playwright/test'

test('Supervisor profile edits preserve Review navigation, current identity and estate guard', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('textbox', { name: 'User ID' }).fill('USR-003')
  await page.getByLabel('Password', { exact: true }).fill('tealeaf-dev-only')
  await page.getByRole('button', { name: 'Log In', exact: true }).click()
  const nav = page.getByRole('navigation', { name: 'Main' })
  await nav.getByRole('link', { name: 'My Profile', exact: true }).click()
  await page.getByRole('textbox', { name: /Full name/ }).fill('Updated Review Supervisor')
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('en')
  await page.getByRole('button', { name: 'Save details' }).click()
  await expect(page.getByRole('heading', { name: 'Updated Review Supervisor', exact: true })).toBeVisible()
  const identity = await page.evaluate(() => JSON.parse(sessionStorage.getItem('tealeaf.session')!).user)
  expect(identity).toMatchObject({ id: 'USR-003', role: 'SUPERVISOR', fullName: 'Updated Review Supervisor', estateIds: ['EST-002'] })
  await nav.getByRole('link', { name: 'Observation Review', exact: true }).click()
  await expect(page).toHaveURL(/\/review\/queue$/)
  await expect(page.getByRole('link', { name: 'OBS-005', exact: true })).toBeVisible()
  await nav.getByRole('link', { name: 'My Profile', exact: true }).click()
  await expect(page.getByRole('textbox', { name: /Full name/ })).toHaveValue('Updated Review Supervisor')
  await page.goto('/review/observations/OBS-011')
  await expect(page.getByText('This observation is unavailable in your estate scope.', { exact: true })).toBeVisible()
  await page.goto('/admin/users')
  await expect(page.getByRole('heading', { name: 'Access denied', exact: true })).toBeVisible()
  await expect(page.getByRole('table', { name: 'Users', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Access denied', exact: true })).toBeVisible()
  await expect(page.getByRole('table', { name: 'Users', exact: true })).toHaveCount(0)
})
