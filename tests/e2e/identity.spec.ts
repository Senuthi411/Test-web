for (const width of [1440, 390]) {
  test(`Identity screens render without page overflow at ${width}px`, async ({ page }) => {
    test.setTimeout(60_000)
    await page.setViewportSize({ width, height: 900 })
    await signIn(page)
    const paths = [
      '/admin', '/admin/users', '/admin/users/new', '/admin/users/USR-001',
      '/admin/users/USR-005/edit', '/admin/users/USR-005/scope', '/admin/roles',
      '/admin/roles/administrator', '/admin/estates', '/admin/estates/EST-001',
      '/admin/divisions', '/admin/divisions/DIV-001', '/admin/device-sessions',
      '/admin/device-sessions/DS-3012/recovery', '/profile', '/forbidden',
    ]
    for (const path of paths) {
      await page.goto(path)
      await expect(page.locator('h1')).toBeVisible()
      await expect(page.getByRole('progressbar')).toHaveCount(0)
      const overflow = await page.evaluate(() => [...document.querySelectorAll('body *')].filter((node) => node.getBoundingClientRect().right > window.innerWidth + 1 && getComputedStyle(node).position !== 'absolute').map((node) => ({ tag: node.tagName, class: node.className, text: node.textContent?.slice(0, 60) })))
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `${path}: ${JSON.stringify(overflow)}`).toBe(true)
    }
  })
}

