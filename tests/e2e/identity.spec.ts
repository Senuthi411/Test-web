test('scope changes require a reason and handle a conflict without saving', async ({ page }) => {
  await signIn(page)
  await page.goto('/admin/users/USR-005/scope')
  const estate = page.getByRole('checkbox', { name: 'Mist Valley Tea Estate (EST-003)' })
  await estate.check()
  await page.getByRole('button', { name: 'Save assignment' }).click()
  let dialog = page.getByRole('dialog', { name: 'Confirm privileged scope change' })
  await dialog.getByRole('button', { name: 'Confirm change' }).click()
  await expect(dialog.getByText('A reason is required for a privileged scope change')).toBeVisible()
  await dialog.getByRole('textbox', { name: 'Reason (required)' }).fill('Cover Mist Valley')
  await dialog.getByRole('button', { name: 'Simulate 409 conflict' }).click()
  await expect(page.getByText('409 · Scope changed elsewhere')).toBeVisible()
  await page.getByRole('button', { name: 'Reload latest scope' }).click()
  await expect(estate).not.toBeChecked()
  await estate.check()
  await page.getByRole('button', { name: 'Save assignment' }).click()
  dialog = page.getByRole('dialog', { name: 'Confirm privileged scope change' })
  await dialog.getByRole('textbox', { name: 'Reason (required)' }).fill('Cover Mist Valley')
  await dialog.getByRole('button', { name: 'Confirm change' }).click()
  await expect(page.getByText('Scope updated', { exact: true })).toBeVisible()
  await expect(estate).toBeChecked()
})

