  await page.getByRole('button', { name: 'Cancel draft', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Cancel ASG-004?' })
  await dialog.getByRole('button', { name: 'Cancel draft', exact: true }).click()
