import { expect, test, type Page } from '@playwright/test'
test.setTimeout(60_000)

async function signIn(page: Page, user = 'USR-003') {
  await page.goto('/login')
  await page.getByRole('textbox', { name: 'User ID' }).fill(user)
  await page.getByLabel('Password', { exact: true }).fill('tealeaf-dev-only')
  await page.getByRole('button', { name: 'Log In', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login/)
}

test('evidence navigation, transforms, expansion, original download and unavailable retry', async ({ page }) => {
  await signIn(page)
  // Evidence Viewer has no sidebar item; its route still opens directly and from review details.
  await page.goto('/observations')
  await expect(page).toHaveURL(/OBS-005\/evidence$/)
  await expect(page.getByRole('heading', { name: 'Observation Evidence Viewer' })).toBeVisible()
  await expect(page.getByRole('status', { name: 'Loading evidence…' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await expect(page.getByLabel('Zoom level')).toHaveText('125%')
  await page.getByRole('button', { name: 'Rotate image' }).click()
  await page.getByRole('button', { name: 'Expand image' }).click()
  await expect(page.getByRole('dialog', { name: 'Expanded evidence image' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /Revision 2/ }).click()
  await expect(page.getByText('Original evidence unchanged. Field notes updated.')).toBeVisible()
  await page.getByRole('link', { name: 'Open original', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download original', exact: true }).first().click()
  expect((await download).suggestedFilename()).toBe('IMG-005-fixture-original.jpg')
  await page.getByRole('button', { name: 'Demo state: evidence unavailable' }).click()
  await expect(page.getByRole('heading', { name: 'Evidence Unavailable', exact: true })).toBeVisible()
  await expect(page.getByText('demo/observations/OBS-005/original.jpg', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Retry loading', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Original Image Viewer' })).toBeVisible()
})

