test('real evidence asset failures preserve provenance and support retry', async ({ page }) => {
  await signIn(page)
  await page.goto('/observations/OBS-005/evidence')
  // Vite inlines small SVGs. Trigger a real browser decode error on the rendered image.
  await page.locator('main img').first().evaluate((image) => { (image as HTMLImageElement).src = 'data:image/svg+xml,%3Cinvalid' })
  await expect(page.getByRole('heading', { name: 'Evidence Unavailable', exact: true })).toBeVisible()
  await expect(page.getByText('IMG-005', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Retry loading', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Observation Evidence Viewer' })).toBeVisible()
})

