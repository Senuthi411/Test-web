  await expect(page.getByRole('heading', { name: 'Assignment unavailable' })).toBeVisible()
  await page.goto('/assignments/ASG-999/edit')
  await expect(page.getByRole('heading', { name: 'Assignment unavailable' })).toBeVisible()
